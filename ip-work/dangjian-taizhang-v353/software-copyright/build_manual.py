# ==================== 十一、常见问题解答 ====================
h('十一、常见问题解答', 1)

h('11.1 人员调离后，为什么其调离前参加的会议仍计入出勤统计？', 2)
para('本软件按会议日期时点判定人员是否在职。人员在调离之前召开的会议，其当时属于在职人员，'
     '应当计入考勤；调离之后的会议才不计入。这样处理可以保证历史台账完整、统计结果贴近实际情况。')

h('11.2 借调人员是否需要维护状态？', 2)
para('建议维护。借调人员组织关系仍在本支部，在"组织架构"页面会予以展示并标注"借调"；'
     '而在出勤统计中，借调期间的会议不计入其考勤，借调结束改回在职后自回归日期起恢复计入。'
     '因此准确记录借调与回归日期，可保证统计结果正确。')

h('11.3 修改人员所在党小组后，以前的出勤对比统计会变吗？', 2)
para('不会。会议记录保存时已写入参会人员当时的党小组快照，出勤对比按快照统计，'
     '因此后续调整人员党小组不会影响此前已记录会议的统计结果。')

h('11.4 为什么会议总数与会议记录的条数不一致？', 2)
para('因为会议总数按"套会拆开"口径统计。一条会议记录可能包含多个会议类型（合并召开），'
     '此时会按类型分别计次，因此会议总数会大于会议记录条数。详见第 10.1 节。')

h('11.5 切换数据看板年份后，为什么"在职党员总数"会变化？', 2)
para('该指标按所选年度的时点统计：选择当前年份时为"截至目前"的在职人数，选择历史年份时为该年'
     '年末时点的在职人数。不同年份的人员状态不同，因此数值会随年份变化。')

h('11.6 数据看板某年度没有数据，页面显示什么？', 2)
para('当所选年度没有会议或谈心谈话记录时，对应图表区域会显示"该年度暂无会议记录"'
     '"该年度暂无出勤记录""该年度暂无谈心谈话记录"等提示文字，不会显示空白坐标系。')

h('11.7 安装版与绿色版的数据是否互通？', 2)
para('不互通。两者的数据保存目录相互独立。若需在两版本之间迁移数据，'
     '请先在原版本中通过"数据管理"导出备份文件，再在新版本中导入恢复。')

h('11.8 为什么在浏览器中打开时，定时自动备份与自动融合不可用？', 2)
para('定时自动备份与定时自动融合依赖桌面应用的文件系统访问能力。在浏览器模式下，'
     '这两项功能会自动降级，页面会给出提示，此时请使用页面上的手动导出备份与手动融合功能。')

h('11.9 能否同时打开多个软件窗口录入数据？', 2)
para('不建议。本软件已限制同一数据目录重复启动：重复启动时会自动聚焦到已打开的窗口，'
     '以避免多个实例同时写入同一份数据造成数据异常。')

h('11.10 误将人员状态标记为借调或调离，如何恢复？', 2)
