# ==================== 十、统计口径说明 ====================
h('十、统计口径说明', 1)
para('为保证会议出勤、数据看板与导出台账三者的统计结果一致，本软件对关键统计指标统一了口径。'
     '本章集中说明各口径的定义与计算方式，便于使用人员核对数据。')

h('10.1 会议次数（套会拆开计次）', 2)
para('实际工作中常出现多类会议合并召开的情况（如支部党员大会与党课同期召开）。'
     '为使统计与实际召开次数一致，本软件的会议次数按"套会拆开"方式计次：')
bullet('一条会议记录中，除党小组会外的每个会议类型各计 1 次；')
bullet('党小组会按该条记录关联的党小组数计次，未关联党小组时计 1 次。')
para('示例：某条会议记录的类型为"支部党员大会、党小组会（3 个党小组参加）、党课、主题党日活动"，'
     '则该条记录计 1 + 3 + 1 + 1 = 6 次。采用该口径后，会议总数等于各会议类型次数之和，'
     '也等于月度会议趋势中各月次数之和，三项指标相互自洽。')

h('10.2 出勤率（按会议日期时点判定在职）', 2)
para('出勤率按"会议日期时点在职"的时间线口径统计，即依据人员的状态变更历史，判断其在每场会议'
     '召开当日是否属于在职人员，而非依据人员当前状态。具体规则如下：')
table(
    ['场景', '是否计入该场会议的考勤'],
    [
        ['在职期间召开的会议', '计入（正常参与应到与实到统计）'],
        ['调离 / 借调 / 离职期间召开的会议', '不计入（该人员此场会议不进应到，也不进实到）'],
        ['状态变更日期之前的会议', '计入（离开之前的会议照常统计）'],
        ['状态改回在职之后的会议', '计入（自回归日期起恢复统计）'],
        ['列席人员', '计入实到（视为出席）'],
        ['临时人员（未匹配人员库）', '始终不计入'],
    ],
    widths=[6.0, 9.6],
)
para('平均出勤率的计算方式为：该年度全部会议的在职出席人次 ÷ 在职应到人次 × 100%。'
     '在数据看板中，鼠标悬停"平均出勤率"指标卡即可查看该说明。')

h('10.3 统计行范围', 2)
para('出勤率排行、参会考勤统计等以人员为行的统计表，其行范围取"统计期内任一会议日期时点在职"'
     '的人员，包含期内已调离、借调中以及借调后回归的人员，以保证历史台账的完整性；'
     '每一行中的各场会议再按各自会议日期单独判定是否计入。')

h('10.4 在职党员总数', 2)
para('"在职党员总数"指所选年度时点的在职党员人数：选择当前年份时按"截至目前"统计，'
     '选择历史年份时按该年年末时点统计。统计时同时考虑人员的入库时间与状态变更历史，'
     '该时点尚未入库、处于借调期间或已调离、离职的人员不计入。切换年份后该指标随之变化。')

h('10.5 组织信息快照', 2)
para('为避免人员岗位调整导致历史统计被改写，本软件在保存会议记录时，会同时保存每位参会人员'
     '当时的部门／支部、部室与党小组信息（即"快照"）。统计与导出时优先采用快照数据；'
     '对升级前没有快照的历史记录，则回退使用人员当前的信息。因此，'
     '调整个别人员的部门或党小组后，此前已记录的会议统计结果不会发生变化。')

